#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const DELETE_ORDER = [
  "ingest_jobs",
  "class_offerings",
  "cross_listings",
  "reverse_index",
  "articulation_group_members",
  "articulation_course_groups",
  "articulations",
  "courses",
  "terms",
  "institutions",
];
const IMPORT_TABLES = new Set(DELETE_ORDER);

const [inputArg = "data/assist.db", outputArg = "d1_import.sql"] = process.argv.slice(2);
const inputPath = resolve(inputArg);
const outputPath = resolve(outputArg);

if (!existsSync(inputPath)) {
  console.error(`SQLite database not found: ${inputPath}`);
  process.exit(1);
}

const dump = spawnSync("sqlite3", [inputPath, ".dump"], {
  encoding: "utf8",
  maxBuffer: 1024 * 1024 * 1024,
});

if (dump.error) {
  console.error(
    "Failed to run sqlite3. Install the SQLite CLI, then rerun this script.",
  );
  console.error(dump.error.message);
  process.exit(1);
}

if (dump.status !== 0) {
  console.error(dump.stderr || "sqlite3 .dump failed");
  process.exit(dump.status || 1);
}

const inserts = dump.stdout
  .split(/\r?\n/)
  .filter((line) => {
    const match = /^INSERT INTO "?([^"\s(]+)"?/i.exec(line.trim());
    return Boolean(match && IMPORT_TABLES.has(match[1]));
  });

const output = [
  "-- Generated by scripts/dump-sqlite-for-d1.mjs",
  "-- Apply migrations/0001_schema.sql before importing this file.",
  "BEGIN TRANSACTION;",
  ...DELETE_ORDER.map((table) => `DELETE FROM ${table};`),
  ...inserts,
  "COMMIT;",
  "",
].join("\n");

writeFileSync(outputPath, output, "utf8");
console.log(`Wrote ${inserts.length} INSERT statements to ${outputPath}`);
