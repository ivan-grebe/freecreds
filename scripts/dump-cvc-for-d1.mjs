#!/usr/bin/env node
import { spawn } from "node:child_process";
import { createWriteStream, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createInterface } from "node:readline";

const [inputArg = "data/assist.db", outputArg = "d1_cvc_import", termsArg = ""] =
  process.argv.slice(2);
const inputPath = resolve(inputArg);
const outputDir = resolve(outputArg.replace(/\.sql$/i, ""));
const manifestPath = join(outputDir, "manifest.json");

if (!existsSync(inputPath)) {
  console.error(`SQLite database not found: ${inputPath}`);
  process.exit(1);
}

const termCodes = termsArg
  .split(",")
  .map((term) => term.trim().toUpperCase())
  .filter(Boolean);

if (!termCodes.length || termCodes.some((term) => !/^(SP|SU|FA|WI)\d{2}$/.test(term))) {
  console.error("Expected comma-separated term codes, for example: FA26,WI27,SP27");
  process.exit(1);
}

function clean(column) {
  return `replace(replace(replace(${column}, char(9), ' '), char(10), ' '), char(13), ' ')`;
}

function sqlString(value) {
  return `'${value.replace(/'/g, "''")}'`;
}

function writeLine(stream, line) {
  return new Promise((resolveWrite) => {
    if (stream.write(`${line}\n`)) {
      resolveWrite();
    } else {
      stream.once("drain", resolveWrite);
    }
  });
}

function byteLength(line) {
  return Buffer.byteLength(`${line}\n`, "utf8");
}

function exportScript() {
  const termList = termCodes.map(sqlString).join(",");
  return `
.headers off
.mode list
SELECT 'INSERT INTO terms (code, label, season, year, start_date, end_date) VALUES ('
       || quote(${clean("code")}) || ', '
       || quote(${clean("label")}) || ', '
       || quote(${clean("season")}) || ', '
       || year || ', '
       || quote(${clean("start_date")}) || ', '
       || quote(${clean("end_date")}) || ') '
       || 'ON CONFLICT(code) DO UPDATE SET '
       || 'label=excluded.label, '
       || 'season=excluded.season, '
       || 'year=excluded.year, '
       || 'start_date=COALESCE(excluded.start_date, terms.start_date), '
       || 'end_date=COALESCE(excluded.end_date, terms.end_date);'
FROM terms
WHERE code IN (${termList})
ORDER BY code;
SELECT 'INSERT INTO class_offerings '
       || '(institution_id, course_id, prefix, number, term_id, modality, source, source_ref, fetched_at) VALUES ('
       || co.institution_id || ', NULL, '
       || quote(${clean("co.prefix")}) || ', '
       || quote(${clean("co.number")}) || ', '
       || '(SELECT id FROM terms WHERE code = ' || quote(${clean("t.code")}) || '), '
       || quote(${clean("co.modality")}) || ', '
       || quote(${clean("co.source")}) || ', '
       || quote(${clean("co.source_ref")}) || ', '
       || quote(${clean("co.fetched_at")}) || ') '
       || 'ON CONFLICT(institution_id, prefix, number, term_id, source_ref) DO UPDATE SET '
       || 'course_id = NULL, '
       || 'modality = excluded.modality, '
       || 'fetched_at = excluded.fetched_at;'
FROM class_offerings co
JOIN terms t ON t.id = co.term_id
WHERE co.source = 'cvc'
  AND t.code IN (${termList})
ORDER BY t.code, co.institution_id, co.prefix, co.number, co.source_ref;
`;
}

async function main() {
  if (existsSync(outputDir)) {
    rmSync(outputDir, { recursive: true, force: true });
  }
  mkdirSync(outputDir, { recursive: true });

  const filename = "part-001.sql";
  const output = createWriteStream(join(outputDir, filename), { encoding: "utf8" });
  let bytes = 0;
  let inserts = 0;
  let termInserts = 0;
  let offeringInserts = 0;

  async function emit(line) {
    await writeLine(output, line);
    bytes += byteLength(line);
  }

  await emit("-- Generated by scripts/dump-cvc-for-d1.mjs");
  await emit("-- CVC-only D1 refresh: terms + class_offerings for selected terms.");

  const sqlite = spawn("sqlite3", [inputPath], {
    stdio: ["pipe", "pipe", "pipe"],
    shell: process.platform === "win32",
  });

  sqlite.on("error", (err) => {
    console.error("Failed to run sqlite3. Install the SQLite CLI, then rerun this script.");
    console.error(err.message);
    process.exit(1);
  });

  sqlite.stdin.end(exportScript());

  let stderr = "";
  sqlite.stderr.setEncoding("utf8");
  sqlite.stderr.on("data", (chunk) => {
    stderr += chunk;
  });
  const closePromise = new Promise((resolveClose) => {
    sqlite.once("close", resolveClose);
  });

  const lines = createInterface({
    input: sqlite.stdout,
    crlfDelay: Infinity,
  });

  await emit(
    `DELETE FROM class_offerings
WHERE source = 'cvc'
  AND term_id IN (SELECT id FROM terms WHERE code IN (${termCodes.map(sqlString).join(",")}));`,
  );

  for await (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      continue;
    }
    await emit(trimmed);
    inserts += 1;
    if (trimmed.startsWith("INSERT INTO terms ")) {
      termInserts += 1;
    } else if (trimmed.startsWith("INSERT INTO class_offerings ")) {
      offeringInserts += 1;
    }
  }

  const exitCode = await closePromise;
  if (exitCode !== 0) {
    output.end();
    console.error(stderr || "sqlite3 export failed");
    process.exit(typeof exitCode === "number" ? exitCode : 1);
  }

  output.end();
  await new Promise((resolveFinish) => output.on("finish", resolveFinish));

  writeFileSync(
    manifestPath,
    JSON.stringify({
      input: inputPath,
      terms: termCodes,
      mode: "cvc-only",
      parts: [{ filename, inserts, bytes }],
      term_inserts: termInserts,
      class_offering_inserts: offeringInserts,
    }, null, 2),
    "utf8",
  );

  console.log(
    `Wrote CVC import for ${termCodes.join(", ")}: `
    + `${termInserts} terms, ${offeringInserts} class_offerings.`,
  );
}

await main();
