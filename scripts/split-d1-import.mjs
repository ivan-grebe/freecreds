#!/usr/bin/env node
import { createReadStream, createWriteStream, existsSync, mkdirSync, rmSync, renameSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createInterface } from "node:readline";

const [inputArg = "d1_import"] = process.argv.slice(2);
const inputDir = resolve(inputArg);
const manifestPath = join(inputDir, "manifest.json");
const outputDir = `${inputDir}.split`;
const MAX_PART_BYTES = Number(process.env.D1_IMPORT_PART_BYTES || 4_000_000_000);
const MAX_PART_INSERTS = Number(process.env.D1_IMPORT_PART_INSERTS || 250_000);

if (!existsSync(manifestPath)) {
  console.error(`Import manifest not found: ${manifestPath}`);
  process.exit(1);
}

function byteLength(line) {
  return Buffer.byteLength(`${line}\n`, "utf8");
}

function isInsert(line) {
  return /^INSERT INTO "?[A-Za-z_][A-Za-z0-9_]*"?\s+VALUES/i.test(line.trim());
}

function isDelete(line) {
  return /^DELETE FROM "?[A-Za-z_][A-Za-z0-9_]*"?;$/i.test(line.trim());
}

function writeLine(stream, line) {
  return new Promise((resolveWrite) => {
    if (stream.write(`${line}\n`)) {
      resolveWrite();
    } else {
      stream.once("drain", resolveWrite);
    }
  });
}

async function closePart(part) {
  if (!part) return;
  part.stream.end();
  await new Promise((resolveFinish) => part.stream.on("finish", resolveFinish));
}

const sourceManifest = JSON.parse(await import("node:fs").then(({ readFileSync }) => (
  readFileSync(manifestPath, "utf8")
)));

if (!Array.isArray(sourceManifest.parts) || !sourceManifest.parts.length) {
  console.error(`No import parts listed in ${manifestPath}`);
  process.exit(1);
}

if (existsSync(outputDir)) {
  rmSync(outputDir, { recursive: true, force: true });
}
mkdirSync(outputDir, { recursive: true });

const parts = [];
let partNumber = 0;
let part = null;
let totalInserts = 0;
let deleteLines = [];

async function openPart(includeDeletes) {
  partNumber += 1;
  const filename = `part-${String(partNumber).padStart(3, "0")}.sql`;
  const stream = createWriteStream(join(outputDir, filename), { encoding: "utf8" });
  const next = { filename, stream, bytes: 0 };

  for (const line of [
    "-- Generated by scripts/split-d1-import.mjs",
    "-- Split from a larger D1 import file.",
  ]) {
    await writeLine(stream, line);
    next.bytes += byteLength(line);
  }

  if (includeDeletes) {
    for (const line of deleteLines) {
      await writeLine(stream, line);
      next.bytes += byteLength(line);
    }
  }

  parts.push({ filename, inserts: 0, bytes: 0 });
  return next;
}

for (const sourcePart of sourceManifest.parts) {
  const sourcePath = join(inputDir, sourcePart.filename);
  const lines = createInterface({
    input: createReadStream(sourcePath, { encoding: "utf8" }),
    crlfDelay: Infinity,
  });

  for await (const line of lines) {
    if (isDelete(line) && !parts.length && !part) {
      deleteLines.push(line);
      continue;
    }
    if (!isInsert(line)) {
      continue;
    }

    if (!part) {
      part = await openPart(true);
    }

    const currentPart = parts.at(-1);
    const needed = byteLength(line);
    if (
      (part.bytes + needed > MAX_PART_BYTES || currentPart.inserts >= MAX_PART_INSERTS)
      && currentPart.inserts > 0
    ) {
      currentPart.bytes = part.bytes;
      await closePart(part);
      part = await openPart(false);
    }

    await writeLine(part.stream, line);
    part.bytes += needed;
    totalInserts += 1;
    parts.at(-1).inserts += 1;

    if (totalInserts % 500_000 === 0) {
      console.error(`split ${totalInserts.toLocaleString()} rows...`);
    }
  }
}

if (part) {
  parts.at(-1).bytes = part.bytes;
  await closePart(part);
}

writeFileSync(
  join(outputDir, "manifest.json"),
  JSON.stringify({
    source_manifest: manifestPath,
    max_part_bytes: MAX_PART_BYTES,
    max_part_inserts: MAX_PART_INSERTS,
    parts,
  }, null, 2),
  "utf8",
);

const backupDir = `${inputDir}.large`;
if (existsSync(backupDir)) {
  rmSync(backupDir, { recursive: true, force: true });
}
renameSync(inputDir, backupDir);
renameSync(outputDir, inputDir);

console.log(`Split ${totalInserts.toLocaleString()} inserts into ${parts.length} file(s).`);
console.log(`Original import moved to ${backupDir}`);
